// Uses an isolated Playwright browser; no user browser profile or sign-ins.
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const glossary = JSON.parse(fs.readFileSync(path.join(root, 'GLOSSARY.json'), 'utf8'));
assert.equal(new Set(glossary.map(x => x.term.toLowerCase())).size, glossary.length);
assert(glossary.every(x => x.term && x.definition));
(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {})});
  try {
    const page = await browser.newPage({viewport:{width:1365,height:1000}});
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const response = await page.goto(process.env.READER_URL || 'http://127.0.0.1:8127');
    assert.equal(response.status(), 200);
    assert.equal(await page.locator('.chapter').count(), 10);
    assert.equal(await page.locator('.chapter:visible').count(), 1);
    assert.equal(await page.locator('.term').count(), glossary.length);
    await page.selectOption('#representation','tensor');
    const clicked = JSON.parse(await page.locator('#inspector-output').textContent());
    assert.deepEqual(clicked.y, [[1]]);
    assert.deepEqual(clicked.x.device, [2]);
    assert.deepEqual(clicked.x.surface, [2]);
    assert(Math.abs(clicked.x.dense[0][1]-9/23)<1e-12);
    assert.deepEqual(clicked.x.history_mask, [[true,true,true,false,false]]);
    await page.selectOption('#outcome','not-clicked');
    const negative = JSON.parse(await page.locator('#inspector-output').textContent());
    assert.deepEqual(negative.y, [[0]]);
    assert.deepEqual(negative.x, clicked.x, 'Changing an outcome must not modify features.');
    await page.selectOption('#outcome','pending');
    const pending = JSON.parse(await page.locator('#inspector-output').textContent());
    assert.equal(pending.y, null);
    assert.equal(pending.eligible_for_final_click_training, false);
    assert.deepEqual(pending.x, clicked.x);
    await page.locator('[data-chapter="3"]').click();
    await page.waitForFunction(() => document.querySelector('#chapter-4').hidden === false);
    assert.equal(await page.locator('.chapter:visible').count(),1);
    assert.equal(await page.locator('[aria-current="page"]').count(),1);
    assert((await page.locator('#chapter-4').innerText()).includes('09:59:58'));
    await page.locator('#next').click();
    await page.waitForFunction(() => !document.querySelector('#chapter-5').hidden);
    await page.locator('#previous').click();
    await page.waitForFunction(() => !document.querySelector('#chapter-4').hidden);
    await page.locator('[data-chapter="9"]').click();
    await page.locator('#glossary-search').fill('attribution');
    assert(await page.locator('.term:visible').count()>0);
    assert(await page.locator('.term:visible').count()<glossary.length);
    await page.locator('#glossary-search').fill('no-such-term-xyz');
    assert.equal(await page.locator('.term:visible').count(),0);
    await page.locator('#glossary-search').fill('');
    assert.equal(await page.locator('.term:visible').count(),glossary.length);
    await page.reload();
    assert.equal(await page.locator('#glossary').isVisible(),true,'Chapter deep link must survive reload.');
    await page.setViewportSize({width:390,height:844});
    await page.locator('#menu-toggle').click();
    assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'),'true');
    await page.locator('[data-chapter="0"]').click();
    await page.waitForFunction(() => !document.querySelector('#chapter-1').hidden);
    assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'),'false');
    for (const id of ['chapter-1','chapter-4','chapter-5','glossary']) {
      await page.evaluate(id => { location.hash=id; },id);
      await page.waitForFunction(id => !document.getElementById(id).hidden,id);
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1), `No page-level overflow at ${id}.`);
    }
    await page.emulateMedia({media:'print'});
    assert.equal(await page.locator('.chapter:visible').count(),10,'Printing must include all chapters.');
    await page.emulateMedia({media:'screen'});
    await page.setViewportSize({width:1365,height:1000});
    await page.evaluate(() => {location.hash='chapter-1';window.scrollTo(0,0);});
    await page.screenshot({path:'/tmp/ads-reader-desktop.png',fullPage:false});
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(() => window.scrollTo(0,0));
    await page.screenshot({path:'/tmp/ads-reader-mobile.png',fullPage:false});
    assert.deepEqual(errors,[]);
    const links = await page.locator('a[href]').evaluateAll(elements => elements.map(x=>x.getAttribute('href')).filter(x=>!x.startsWith('http')&&!x.startsWith('#')));
    for (const link of new Set(links)) assert.equal((await page.request.get(new URL(link,page.url()).href)).status(),200,`Local link: ${link}`);
    console.log(`PASS: 10 chapters, ${glossary.length} definitions, all outcome states, stable features, navigation, deep links, mobile, print, local links and no browser errors.`);
  } finally { await browser.close(); }
})().catch(e => {console.error(e);process.exitCode=1;});
